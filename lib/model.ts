// Token Radar, model radar-2.
//
// One sealed snapshot in, one ranked board out. The board covers every slug
// in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token protocols below the floor with the most TVL: the early rows the
// radar exists to find. Live-token protocols are kept apart and shown with
// the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, never from a
// hardcoded list of names:
//
//   multiple   = the category's median mcap/TVL among live-token protocols
//                in this same snapshot (at least 5 comps), else the overall
//                median 0.2138 across all 128 live-token protocols.
//                Medians, not means: one outlier (a $2.6B mcap on $6.6M TVL)
//                must not move a whole category.
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4
//                (age unknown: 365 days)
//   implied    = max(1, round(base x growthMult x maturity))
//
// Calibrated multiples (live-token comps in snapshot 2026-11-14):
//   Basis Trading 0.6544 (n=7) | Dexs 0.3424 (n=11) | RWA 0.2748 (n=9)
//   Yield 0.1914 (n=9) | Lending 0.1324 (n=15) | all others 0.2138.
// The starter used a flat 0.25 for every protocol. That overvalues Lending
// and Yield and undervalues Dexs, RWA and Basis Trading against the market's
// own ratios. This model keeps the starter's growth and maturity shape and
// changes only the multiple, so the ranking moves where the evidence moves.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  overall_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  overall_multiple: 0.2138,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
};

/** Category multiples, median mcap/TVL where the snapshot holds >= 5 live comps. */
export const CATEGORY_MULTIPLES: Record<string, number> = {
  'Basis Trading': 0.6544,
  Dexs: 0.3424,
  RWA: 0.2748,
  Yield: 0.1914,
  Lending: 0.1324,
};

export const MODEL_VERSION = 'radar-2';

/** Pre-token protocols below the watchlist floor the early radar carries, by TVL. */
export const EARLY_ROWS = 160;

/** Live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

